use alloc::{string::ToString, vec::Vec};

use miden_core::{
    Word,
    deferred::PrecompileLimits,
    proof::{ExecutionProof, HashFunction, PrecompileProof, PrecompileStatus, VmProof},
};
use miden_processor::{
    ExecutionError, ExecutionTrace, ExecutionWitness, PrecompileWitness, VmTraceBudget, VmWitness,
    trace::VmTrace,
};

use crate::PrecompileProvingError;

/// A synchronous, configurable prover for Miden VM execution witnesses and traces.
///
/// This type does not execute programs. It owns proof-generation policy — including the memory
/// budget for materializing a VM execution trace — and consumes artifacts produced by the
/// processor.
#[derive(Debug, Clone, Eq, PartialEq)]
pub struct Prover {
    hash_fn: HashFunction,
    hash_lde_blocks: bool,
    max_prover_memory_bytes: u64,
    max_precompile_prover_memory_bytes: u64,
    verification_precompile_limits: PrecompileLimits,
}

/// The execution artifact consumed by [`Prover::prove`] or [`Prover::prove_full`].
#[derive(Debug)]
pub enum ProvingInput {
    /// A recorded execution witness whose VM trace the prover will build.
    Witness(ExecutionWitness),
    /// A materialized execution trace paired with its optional precompile witness.
    Trace(ExecutionTrace),
}

impl From<ExecutionWitness> for ProvingInput {
    fn from(witness: ExecutionWitness) -> Self {
        Self::Witness(witness)
    }
}

impl From<ExecutionTrace> for ProvingInput {
    fn from(trace: ExecutionTrace) -> Self {
        Self::Trace(trace)
    }
}

impl Prover {
    /// Default maximum modelled peak memory, in bytes, for proving a VM execution trace.
    ///
    /// This bounds the approximate lifted-STARK VM allocations modelled by
    /// `miden_stark::memory`, including the fixed And8 preprocessed setup. It is not a
    /// total process-RSS or allocator cap. The precompile prover's memory is bounded separately
    /// by [`max_precompile_prover_memory_bytes`](Self::max_precompile_prover_memory_bytes).
    pub const DEFAULT_MAX_PROVER_MEMORY_BYTES: u64 =
        miden_vm_stark::memory::DEFAULT_MAX_PROVER_MEMORY_BYTES;

    /// Default maximum modelled peak memory, in bytes, for proving a precompile witness.
    pub const DEFAULT_MAX_PRECOMPILE_PROVER_MEMORY_BYTES: u64 =
        miden_precompiles_stark::prover::DEFAULT_MAX_PRECOMPILE_PROVER_MEMORY_BYTES;

    /// Creates a prover with the canonical proof-generation configuration.
    pub fn new() -> Self {
        Self {
            hash_fn: HashFunction::Eidos,
            hash_lde_blocks: false,
            max_prover_memory_bytes: Self::DEFAULT_MAX_PROVER_MEMORY_BYTES,
            max_precompile_prover_memory_bytes: Self::DEFAULT_MAX_PRECOMPILE_PROVER_MEMORY_BYTES,
            verification_precompile_limits:
                miden_precompiles::default_verification_precompile_limits(),
        }
    }

    /// Sets the verification policy applied independently to each precompile witness.
    #[must_use]
    pub fn with_verification_precompile_limits(mut self, limits: PrecompileLimits) -> Self {
        self.verification_precompile_limits = limits;
        self
    }

    /// Sets the hash function used for proofs generated by this prover.
    #[must_use]
    pub const fn with_hash_fn(mut self, hash_fn: HashFunction) -> Self {
        self.hash_fn = hash_fn;
        self
    }

    /// Sets whether MVM proving hashes completed blocks during the final trace LDE.
    ///
    /// Disabled by default. This changes scheduling while preserving commitments and proof format.
    /// Hash configurations without block support use eager hashing. PVM proving is unaffected.
    #[must_use]
    pub const fn with_hash_lde_blocks(mut self, enabled: bool) -> Self {
        self.hash_lde_blocks = enabled;
        self
    }

    /// Sets the maximum modelled peak memory, in bytes, for proving a VM execution trace.
    ///
    /// See [`Self::DEFAULT_MAX_PROVER_MEMORY_BYTES`] for the model's scope and exclusions.
    #[must_use]
    pub const fn with_max_prover_memory_bytes(mut self, max_prover_memory_bytes: u64) -> Self {
        self.max_prover_memory_bytes = max_prover_memory_bytes;
        self
    }

    /// Returns the maximum modelled peak memory, in bytes, for proving a VM execution trace.
    pub const fn max_prover_memory_bytes(&self) -> u64 {
        self.max_prover_memory_bytes
    }

    /// Returns the canonical VM trace-building budget for this prover's memory limit.
    ///
    /// Pass this to `Processor::build_trace` to apply the same VM relation model and
    /// byte limit as this prover. The precompile proving budget is configured independently.
    pub fn trace_budget(&self) -> VmTraceBudget {
        miden_vm_stark::memory::canonical_budget(self.max_prover_memory_bytes)
    }

    /// Sets the maximum modelled peak memory, in bytes, for proving a precompile witness.
    #[must_use]
    pub const fn with_max_precompile_prover_memory_bytes(
        mut self,
        max_precompile_prover_memory_bytes: u64,
    ) -> Self {
        self.max_precompile_prover_memory_bytes = max_precompile_prover_memory_bytes;
        self
    }

    /// Returns the maximum modelled peak memory, in bytes, for proving a precompile witness.
    pub const fn max_precompile_prover_memory_bytes(&self) -> u64 {
        self.max_precompile_prover_memory_bytes
    }

    /// Proves the VM portion of a recorded witness or materialized execution trace.
    ///
    /// If the execution authenticated deferred precompile work, the returned proof carries its
    /// portable singleton witness for later proving. Otherwise, it is complete.
    ///
    /// The prover builds traces from witnesses under its configured budget and checks the padded
    /// shape of materialized traces against the same budget before proof generation.
    pub fn prove(&self, input: impl Into<ProvingInput>) -> Result<ExecutionProof, ProverError> {
        let (trace, precompile) = self.prepare_input(input.into())?;
        let vm = self.prove_vm_trace(trace)?;
        let status = precompile.map_or(PrecompileStatus::Empty, PrecompileStatus::Deferred);
        Ok(ExecutionProof::new(vm, status))
    }

    /// Proves a recorded witness or materialized execution trace and all authenticated precompile
    /// work.
    ///
    /// The returned execution proof has an empty or proven precompile status. The VM trace is
    /// subject to the same budget checks as in [`Self::prove`].
    pub fn prove_full(
        &self,
        input: impl Into<ProvingInput>,
    ) -> Result<ExecutionProof, ProverError> {
        let (trace, precompile) = self.prepare_input(input.into())?;
        let precompile_root = trace.precompile_root();
        let vm = self.prove_vm_trace(trace)?;
        let precompile = precompile
            .map(|witness| self.prove_precompile_for_root(witness, precompile_root))
            .transpose()?;
        let status = precompile.map_or(PrecompileStatus::Empty, PrecompileStatus::Proven);
        Ok(ExecutionProof::new(vm, status))
    }

    /// Proves a VM witness that does not authenticate deferred precompile work.
    ///
    /// The returned execution proof has an empty precompile status. Use [`Self::prove`] or
    /// [`Self::prove_full`] when the original execution witness contains precompile work.
    pub fn prove_vm_witness(&self, witness: VmWitness) -> Result<ExecutionProof, ProverError> {
        if witness.has_precompiles() {
            return Err(ProverError::VmWitnessHasPrecompiles);
        }

        let vm = self.prove_vm_trace(self.build_vm_trace(witness)?)?;
        Ok(ExecutionProof::new(vm, PrecompileStatus::Empty))
    }

    fn prepare_input(
        &self,
        input: ProvingInput,
    ) -> Result<(VmTrace, Option<PrecompileWitness>), ProverError> {
        match input {
            ProvingInput::Witness(witness) => {
                let (vm, precompile) = witness.into_parts();
                Ok((self.build_vm_trace(vm)?, precompile))
            },
            ProvingInput::Trace(trace) => Ok(trace.into_parts()),
        }
    }

    fn build_vm_trace(&self, witness: VmWitness) -> Result<VmTrace, ProverError> {
        witness.build_trace(&self.trace_budget()).map_err(ProverError::TraceGeneration)
    }

    /// Proves an owned batch of singleton execution obligations in one STARK.
    ///
    /// The proof preserves the input roots in order, including repeated roots. An empty batch
    /// is rejected, as is a batch exceeding the shared 128-root proof ceiling. Single-execution
    /// proving uses this same path with a one-element vector.
    ///
    /// The configured logical limits apply independently to each witness before session creation.
    /// The batch may exceed those totals collectively; root count and prover memory remain
    /// independent batch-wide ceilings. Conservative memory reservations are checked before
    /// preparing each witness and recording each new Session node, and the modelled proving peak is
    /// checked before trace allocation.
    pub fn prove_precompiles(
        &self,
        witnesses: Vec<PrecompileWitness>,
    ) -> Result<PrecompileProof, ProverError> {
        miden_precompiles_stark::prover::prove_precompiles_with_limits_and_budget(
            witnesses,
            self.hash_fn,
            &self.verification_precompile_limits,
            self.max_precompile_prover_memory_bytes,
        )
        .map_err(ProverError::PrecompileProofGeneration)
    }

    fn prove_precompile_for_root(
        &self,
        witness: PrecompileWitness,
        expected_root: Word,
    ) -> Result<PrecompileProof, ProverError> {
        miden_precompiles_stark::prover::prove_precompile_for_root_with_limits_and_budget(
            witness,
            expected_root,
            self.hash_fn,
            &self.verification_precompile_limits,
            self.max_precompile_prover_memory_bytes,
        )
        .map_err(ProverError::PrecompileProofGeneration)
    }

    /// Proves a fully materialized VM trace.
    ///
    /// Buffered and overlapped trace construction share this private implementation so STARK
    /// generation and VM proof packaging cannot diverge.
    fn prove_vm_trace(&self, trace: VmTrace) -> Result<VmProof, ProverError> {
        let budget = self.trace_budget();
        let estimated_bytes = budget
            .prover_peak_bytes(trace.trace_len_summary().padded_heights())
            .ok_or(ProverError::VmProofGeneration(ExecutionError::ProverMemoryExceeded {
                estimated_bytes: u64::MAX,
                budget_bytes: self.max_prover_memory_bytes,
            }))?;
        if estimated_bytes > self.max_prover_memory_bytes {
            return Err(ProverError::VmProofGeneration(ExecutionError::ProverMemoryExceeded {
                estimated_bytes,
                budget_bytes: self.max_prover_memory_bytes,
            }));
        }
        miden_vm_stark::prover::prove(trace, self.hash_fn, self.hash_lde_blocks).map_err(|error| {
            ProverError::VmProofGeneration(ExecutionError::ProvingError(error.to_string()))
        })
    }
}

impl Default for Prover {
    fn default() -> Self {
        Self::new()
    }
}

/// Errors produced while proving execution artifacts.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum ProverError {
    /// The VM witness authenticates deferred precompile work that this proving path cannot carry.
    #[error("VM witness contains deferred precompile work")]
    VmWitnessHasPrecompiles,
    /// The processor witness could not be materialized into a valid execution trace.
    #[error("failed to materialize VM execution trace: {0}")]
    TraceGeneration(#[source] ExecutionError),
    /// The materialized VM trace could not be proved.
    #[error("failed to prove VM execution trace: {0}")]
    VmProofGeneration(#[source] ExecutionError),
    /// The deferred precompile witness could not be proved.
    #[error("failed to prove precompile witness: {0}")]
    PrecompileProofGeneration(#[source] PrecompileProvingError),
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prover_uses_canonical_default_and_allows_hash_override() {
        let prover = Prover::new();
        assert_eq!(prover.hash_fn, HashFunction::Eidos);

        let prover = prover.with_hash_fn(HashFunction::Blake3_256);
        assert_eq!(prover.hash_fn, HashFunction::Blake3_256);
    }

    #[test]
    fn prover_uses_canonical_memory_budget_and_allows_override() {
        let prover = Prover::new();
        assert_eq!(prover.max_prover_memory_bytes(), Prover::DEFAULT_MAX_PROVER_MEMORY_BYTES);

        let prover = prover.with_max_prover_memory_bytes(1 << 20);
        assert_eq!(prover.max_prover_memory_bytes(), 1 << 20);
    }

    #[test]
    fn prover_uses_canonical_precompile_memory_budget_and_allows_override() {
        let prover = Prover::new();
        assert_eq!(
            prover.max_precompile_prover_memory_bytes(),
            Prover::DEFAULT_MAX_PRECOMPILE_PROVER_MEMORY_BYTES
        );

        let prover = prover.with_max_precompile_prover_memory_bytes(1 << 20);
        assert_eq!(prover.max_precompile_prover_memory_bytes(), 1 << 20);
    }

    /// A minimal non-`TRUE` precompile witness: no keccak/uint/EC ops, just the fixed session
    /// installs plus one trivial `AND` node. Its chiplet traces still have nonzero (fixed-minimum)
    /// heights, so it is enough to exercise the memory-budget check without a full precompile
    /// execution fixture.
    fn trivial_precompile_witness() -> PrecompileWitness {
        use alloc::sync::Arc;

        use miden_core::deferred::{
            DeferredState, Node, PrecompileLimits, PrecompileRegistry, TRUE_DIGEST,
        };

        let registry = Arc::new(PrecompileRegistry::new());
        let mut state = DeferredState::new(registry, PrecompileLimits::new(u64::MAX))
            .expect("empty registry state should initialize");
        let statement = state
            .register(Node::and(TRUE_DIGEST, TRUE_DIGEST))
            .expect("trivial AND node should register");
        state
            .log_statement(statement)
            .expect("trivial statement should log into the deferred root");
        state
            .into_witness(&PrecompileLimits::new(u64::MAX))
            .expect("trivial deferred state should export")
            .expect("non-TRUE root should export a witness")
    }

    #[test]
    fn prove_precompiles_applies_the_configured_memory_budget() {
        // A 1-byte budget must reject even the minimal chiplet trace shapes, and the returned
        // error carries the configured budget. Exact-boundary behavior is covered by
        // `miden-precompiles-stark`.
        let err = Prover::new()
            .with_max_precompile_prover_memory_bytes(1)
            .prove_precompiles(alloc::vec![trivial_precompile_witness()])
            .expect_err("a 1-byte budget must reject even the minimal chiplet trace shapes");
        assert!(
            matches!(
                err,
                ProverError::PrecompileProofGeneration(
                    PrecompileProvingError::MemoryBudgetExceeded { budget_bytes: 1, .. }
                )
            ),
            "expected MemoryBudgetExceeded {{ budget_bytes: 1, .. }}, got: {err:?}"
        );
    }
}
