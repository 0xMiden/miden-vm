//! Generates PVM fixed-environment boundary correction MASM from native bus messages.

use std::{
    fmt::Write as _,
    format,
    string::{String, ToString},
    vec,
    vec::Vec,
};

use miden_precompiles_air::{
    fixed::{self, FixedEcGroup, FixedUint},
    relations::MAX_MESSAGE_WIDTH,
};

const MODULE: &str = include_str!("masm/fixed_boundary.masm.tpl");
const UINTVAL: &str = include_str!("masm/fixed_uintval.masm.tpl");
const ECGROUP: &str = include_str!("masm/fixed_ecgroup.masm.tpl");

pub(crate) fn render_fixed_boundary() -> Result<String, String> {
    // compute_bus_gamma uses an addition chain for beta^18. Changing the message width requires
    // updating that chain and this guard together.
    if MAX_MESSAGE_WIDTH != 18 {
        return Err("update compute_bus_gamma for the new PVM message width".into());
    }
    let mut uints: Vec<_> = fixed::fixed_uint_records().collect();
    // The sum also accepts native catalogue order. Sorting bounds before dependents, then by
    // address, preserves the accepted executable identity; the field sum does not require it.
    uints.sort_by_key(|entry| (entry.ptr != entry.bound_ptr, entry.ptr));
    let groups: Vec<_> = fixed::fixed_ecgroup_records().collect();
    let body = render_messages(&uints, &groups)?;
    Ok(format!(
        "# Generated by `make regenerate-pvm-constants`. Do not edit.\n\
         # Assembly source: crates/precompiles-verifier/src/masm/fixed_boundary.masm.tpl\n\
         # Message bodies: fixed_uintval.masm.tpl and fixed_ecgroup.masm.tpl (same directory).\n\
         {body}"
    ))
}

fn render_messages(uints: &[FixedUint], groups: &[FixedEcGroup]) -> Result<String, String> {
    let mut uintval_messages = String::new();
    for uint in uints {
        let entry = render_uint(UINTVAL, uint)?;
        uintval_messages.push_str(&entry);
        uintval_messages.push('\n');
    }
    let mut ecgroup_messages = String::new();
    for record in groups {
        let group = &record.message;
        let entry = render_template(
            ECGROUP,
            &[
                ("label".into(), format!("{:?}", record.curve)),
                ("group_ptr".into(), group.group_ptr.to_string()),
                ("a_ptr".into(), group.a_ptr.to_string()),
                ("b_ptr".into(), group.b_ptr.to_string()),
                ("bound_ptr".into(), group.bound_ptr.to_string()),
                ("scalar_bound_ptr".into(), group.scalar_bound_ptr.to_string()),
                ("beta_ptr".into(), group.beta_ptr.to_string()),
                ("lambda_ptr".into(), group.lambda_ptr.to_string()),
            ],
        )?;
        ecgroup_messages.push_str(&entry);
        ecgroup_messages.push('\n');
    }
    render_template(
        MODULE,
        &[
            ("uintval_messages".into(), uintval_messages.trim_end().into()),
            ("ecgroup_messages".into(), ecgroup_messages.trim_end().into()),
        ],
    )
}

/// Supplies `label`, `ptr`, `bound_ptr`, `push_payload`, and `c0` through `c7` to a UintVal
/// template. `push_payload` loads the complete payload. Individual limbs are little-endian; push
/// `c7` first so it is deepest in the payload expected by `fold_uint_val_payload`.
fn render_uint(template: &str, uint: &FixedUint) -> Result<String, String> {
    let mut values = vec![
        ("label".into(), uint.kind.to_string()),
        ("ptr".into(), uint.ptr.to_string()),
        ("bound_ptr".into(), uint.bound_ptr.to_string()),
        ("push_payload".into(), push_uint_payload(uint)),
    ];
    values.extend(
        uint.limbs
            .iter()
            .enumerate()
            .map(|(index, limb)| (format!("c{index}"), format!("0x{limb:08X}"))),
    );
    render_template(template, &values)
}

/// Emits pushes placing `[ptr, bound_ptr, c0, ..., c7]` above the caller's stack.
fn push_uint_payload(uint: &FixedUint) -> String {
    let FixedUint { ptr, bound_ptr, limbs, .. } = uint;
    let mut output = String::new();
    let high = limbs[limbs.len() - 1];
    let repeated = limbs.iter().rev().take_while(|&&limb| limb == high).count();
    // A leading run of large immediates can share one literal via dup. Zero and one already
    // lower to single operations, so leave those pushes intact.
    let remaining = if high > 1 && repeated > 1 {
        writeln!(output, "    push.0x{high:08X}{}", " dup".repeat(repeated - 1)).unwrap();
        limbs.len() - repeated
    } else {
        limbs.len()
    };
    output.push_str("    push");
    for limb in limbs[..remaining].iter().rev() {
        write!(output, ".0x{limb:08X}").unwrap();
    }
    write!(output, ".{bound_ptr}.{ptr}").unwrap();
    output
}

fn render_template(template: &str, values: &[(String, String)]) -> Result<String, String> {
    let mut output = template.to_string();
    for (name, value) in values {
        let placeholder = format!("{{{{{name}}}}}");
        output = output.replace(&placeholder, value);
    }
    if output.contains("{{") || output.contains("}}") {
        return Err("unexpanded fixed-boundary template placeholder".into());
    }
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn uint_template_can_omit_comment_bindings_but_rejects_unknown_bindings() {
        let uint = fixed::fixed_uint_records().next().unwrap();
        let without_comment = UINTVAL
            .lines()
            .filter(|line| !line.trim_start().starts_with('#'))
            .collect::<Vec<_>>()
            .join("\n");
        let rendered = render_uint(&without_comment, &uint).unwrap();
        assert!(rendered.contains("exec.fold_uint_val_payload"));
        let unknown = format!("{without_comment}\n{{{{typo}}}}");
        assert!(render_uint(&unknown, &uint).unwrap_err().contains("unexpanded"));
    }

    #[test]
    fn uint_template_can_load_individual_limbs_in_stack_order() {
        let mut uint = fixed::fixed_uint_records().next().unwrap();
        uint.limbs = [0, 1, 2, 3, 4, 5, 6, 7];
        let rendered = render_uint(
            "push.{{c7}}.{{c6}}.{{c5}}.{{c4}}.{{c3}}.{{c2}}.{{c1}}.{{c0}}.{{bound_ptr}}.{{ptr}}",
            &uint,
        )
        .unwrap();
        assert_eq!(
            rendered,
            format!(
                "push.0x00000007.0x00000006.0x00000005.0x00000004.0x00000003.0x00000002.0x00000001.0x00000000.{}.{}",
                uint.bound_ptr, uint.ptr,
            )
        );
    }
}
