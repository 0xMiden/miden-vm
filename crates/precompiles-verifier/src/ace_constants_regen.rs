//! Regenerates the trusted configuration tables and shared OOD hook for all PVM AIR variants.

use std::{
    collections::BTreeSet,
    fmt::Write as _,
    format, io, println,
    string::{String, ToString},
    vec::Vec,
};

use miden_ace_codegen::{InputKey, LayoutKind};
use miden_air::precompiles::{ChipletAir, PvmAirVariant, security as pvm_security};
use miden_air_definitions::precompiles::relation::{self, CapturedPvmRelation, HeightRule};
use miden_core::{Felt, Word, field::QuadFelt};
use miden_crypto::hash::eidos::{
    BLOCK_LEN as EIDOS_BLOCK_WIDTH, Eidos,
    domains::{GENERIC_FELT_SEQUENCE, LMCS_LEAF},
};
use miden_lifted_air::LiftedAir;

use crate::{
    ace::PvmRecursiveAceCircuit,
    ace_constants::{GENERATED_BY, relation_digest_for_circuit},
    pvm_ood_frames::{PvmOodGeometry, pvm_pipe_lengths, render_pvm_ood_frames},
};

const PARAMETERS_PATH: &str = "../lib/core/asm/sys/pvm/parameters.masm";
const FIXED_BOUNDARY_PATH: &str = "../lib/core/asm/sys/pvm/fixed_boundary.masm";
const VARIANTS_PATH: &str = "../lib/core/asm/sys/pvm/variants.masm";
const OOD_PATH: &str = "../lib/core/asm/sys/pvm/ood_frames.masm";
const READ_START: u32 = 3_225_432_064;
const METADATA_START: u32 = 3_225_452_000;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Mode {
    Check,
    Write,
}

pub fn run(mode: Mode) -> Result<(), String> {
    check_metadata_accessors()?;
    let (num_inputs, _, stream_len) = miden_air::precompiles::protocol::metadata().circuit_shape;
    let stream_end = u64::from(READ_START) + 2 * num_inputs as u64 + stream_len as u64;
    let mut parameters = String::new();
    let mut variants = format!("# GENERATED by `{GENERATED_BY}` — do not edit by hand.\n\n");
    let mut loaders = BTreeSet::new();
    let pipe_lengths = pvm_pipe_lengths();
    let pipe_offset = |width: usize| -> Result<u64, String> {
        let index = pipe_lengths
            .binary_search(&(width / 4))
            .map_err(|_| format!("missing OOD pipe for width {width}"))?;
        Ok(52 + 4 * index as u64)
    };
    let mut ood = String::new();
    for variant in PvmAirVariant::ALL_VARIANTS {
        let captured = CapturedPvmRelation::with_variant(variant).map_err(|e| e.to_string())?;
        let compiled = captured.compile().map_err(|e| e.to_string())?;
        let source = compiled.build_circuit(LayoutKind::Masm).map_err(|e| e.to_string())?;
        let layout = source.layout();
        let circuit = PvmRecursiveAceCircuit::try_from(source.to_ace().map_err(|e| e.to_string())?)
            .map_err(|e| e.to_string())?;
        let relation_digest = relation_digest_for_circuit(&circuit.commitment);
        let pins = miden_air::precompiles::protocol::pins_for(variant);
        let preprocessed_commitment =
            Word::new(pins.preprocessed_commitment.map(Felt::new_unchecked));
        if pins.ace_circuit_digest != circuit.commitment.map(|felt| felt.as_canonical_u64())
            || pins.relation_digest != relation_digest.map(|felt| felt.as_canonical_u64())
            || miden_air::precompiles::protocol::metadata_for(variant).circuit_shape
                != (circuit.num_inputs, circuit.num_eval_gates, circuit.stream_len)
        {
            return Err(format!(
                "PVM variant {} differs from its pinned protocol identity",
                variant.as_u8()
            ));
        }
        let geometry = PvmOodGeometry::from_compiled(compiled.geometry(), layout)?;
        let airs: Vec<_> =
            ChipletAir::all().into_iter().filter(|air| air.is_in_variant(variant)).collect();
        if (airs.len() == 12) != (variant == PvmAirVariant::ALL) {
            return Err("PVM full-variant setup requires exactly twelve AIRs, uniquely".into());
        }
        let shape = miden_air_definitions::precompiles::geometry::air_shape_for(&compiled, variant);
        if shape != miden_air::precompiles::protocol::metadata_for(variant).air_shape {
            return Err(format!(
                "PVM variant {} security shape differs from compiled protocol metadata",
                variant.as_u8()
            ));
        }
        let quotient = miden_lifted_stark::quotient_recomposition_inputs::<Felt>(
            layout.counts.num_quotient_chunks.ilog2() as u8,
            miden_air::precompiles::stark_config::precompile_pcs_params().log_blowup(),
        )
        .map_err(|e| e.to_string())?;
        let pointer = |key| -> Result<u64, String> {
            layout
                .index(key)
                .map(|index| u64::from(READ_START) + 2 * index as u64)
                .ok_or_else(|| format!("missing PVM input {key:?}"))
        };
        let stream_ptr = u64::from(READ_START) + 2 * layout.total_inputs as u64;
        if stream_ptr + circuit.stream_len as u64 > stream_end {
            return Err(format!("variant {} exceeds reserved circuit memory", variant.as_u8()));
        }
        let mut metadata = [0u64; 128];
        metadata[..24].copy_from_slice(&[
            airs.len() as u64,
            circuit.num_inputs as u64,
            circuit.num_eval_gates as u64,
            airs.iter()
                .map(|air| {
                    <ChipletAir as LiftedAir<Felt, QuadFelt>>::max_periodic_length(air)
                        .max(1)
                        .ilog2()
                })
                .max()
                .unwrap() as u64,
            (circuit.stream_len / 8) as u64,
            shape.max_constraint_degree as u64,
            shape.num_composed_constraints as u64,
            shape.num_deep_terms.unwrap() as u64,
            shape.lookup.unwrap().fractions_per_row as u64,
            (geometry.main.iter().sum::<usize>() / 8) as u64,
            (geometry.aux.iter().sum::<usize>() / 8) as u64,
            (geometry.quotient / 8) as u64,
            pointer(InputKey::MultiAirFoldCoeff(0))?,
            quotient.shift_ratio.as_canonical_u64(),
            quotient.first_shift.as_canonical_u64(),
            quotient.first_weight.as_canonical_u64(),
            pointer(InputKey::AuxRandBeta)?,
            pointer(InputKey::Preprocessed { offset: 0, index: 0 })?,
            pointer(InputKey::AuxBusBoundary(0))?,
            pointer(InputKey::Alpha)?,
            stream_ptr,
            geometry.row_felts() as u64,
            (geometry.row_felts() - geometry.quotient * 2) as u64,
            0,
        ]);
        let words = [
            (24, Eidos::init_chaining_word(GENERIC_FELT_SEQUENCE, circuit.stream_len as u32)),
            (28, circuit.commitment),
            (
                32,
                Eidos::init_chaining_word(LMCS_LEAF, geometry.main.iter().sum::<usize>() as u32),
            ),
            (
                36,
                Eidos::init_chaining_word(LMCS_LEAF, geometry.aux.iter().sum::<usize>() as u32),
            ),
            (40, Eidos::init_chaining_word(LMCS_LEAF, geometry.quotient as u32)),
            (44, Word::new(relation_digest)),
            (48, preprocessed_commitment),
        ];
        for (offset, word) in words {
            for (index, value) in word.iter().enumerate() {
                metadata[offset + index] = value.as_canonical_u64();
            }
        }
        metadata[52] = (12 + airs.len() as u64) % 8;
        metadata[53] = (4 + 2 * airs.len() as u64) % 8;
        let mut main_offset = geometry.preprocessed.iter().sum::<usize>() * 2;
        let mut aux_offset = main_offset + geometry.main.iter().sum::<usize>() * 2;
        for (index, air) in airs.iter().enumerate() {
            metadata[56 + index] =
                <ChipletAir as LiftedAir<Felt, QuadFelt>>::max_periodic_length(air)
                    .max(2)
                    .ilog2()
                    .max(1) as u64;
            metadata[68 + index] = air.fixed_log_height().unwrap_or(0) as u64;
            metadata[80 + index] = main_offset as u64;
            metadata[92 + index] = pipe_offset(geometry.main[index])?;
            metadata[104 + index] = aux_offset as u64;
            metadata[116 + index] = pipe_offset(geometry.aux[index])?;
            main_offset += geometry.main[index] * 2;
            aux_offset += geometry.aux[index] * 2;
        }
        writeln!(variants, "proc initialize_{}", variant.as_u8()).unwrap();
        for (index, word) in metadata.as_chunks::<4>().0.iter().enumerate() {
            writeln!(
                variants,
                "    push.{}.{}.{}.{} mem_storew_le.{} dropw",
                word[3],
                word[2],
                word[1],
                word[0],
                METADATA_START + 4 * index as u32
            )
            .unwrap();
        }
        // Select fixed-count loaders once, keeping counters out of every query's hot loop.
        for (name, blocks, offset) in [
            ("ace", metadata[4], 128),
            ("query", metadata[9], 132),
            ("query", metadata[10], 136),
        ] {
            loaders.insert((name, blocks));
            writeln!(
                variants,
                "    procref.load_{name}_{blocks} mem_storew_le.{} dropw",
                METADATA_START + offset
            )
            .unwrap();
        }
        if metadata[11] != 1 {
            return Err("PVM quotient query loader requires one eight-felt block".into());
        }
        variants.push_str("end\n\n");
        if variant == PvmAirVariant::ALL {
            parameters = render_pvm_parameters(
                &geometry,
                &relation::protocol(),
                relation_digest,
                preprocessed_commitment,
            )?;
            ood = render_pvm_ood_frames(&geometry, true)?;
        }
    }
    for (name, blocks) in loaders {
        writeln!(variants, "proc load_{name}_{blocks}").unwrap();
        if name == "query" {
            // The fixed row length also fixes its LMCS frame. Load it here instead of
            // reading the same trusted metadata word again for every query.
            let encoded_len = u32::try_from(blocks * EIDOS_BLOCK_WIDTH as u64)
                .map_err(|_| "PVM query loader length exceeds u32")?;
            let cv = Eidos::init_chaining_word(LMCS_LEAF, encoded_len);
            writeln!(variants, "    push.{}.{}.{}.{}\n    swapw padw", cv[3], cv[2], cv[1], cv[0])
                .unwrap();
        }
        writeln!(variants, "    repeat.{blocks}\n        adv_pipe").unwrap();
        if name == "query" {
            variants.push_str("        horner_eval_base\n");
        }
        variants.push_str("        compress\n    end\nend\n\n");
    }
    variants.push_str("pub proc load()\n    adv_push u32assert dup u32lte.7 assert.err=\"unsupported PVM AIR variant\"\n");
    for bits in 0..7 {
        writeln!(variants, "    dup eq.{bits}\n    if.true drop exec.initialize_{bits} else")
            .unwrap();
    }
    variants.push_str("    drop exec.initialize_7\n");
    for _ in 0..7 {
        variants.push_str("    end\n");
    }
    variants.push_str("end\n");
    for (path, output) in [
        (PARAMETERS_PATH, parameters),
        (FIXED_BOUNDARY_PATH, crate::fixed_boundary_codegen::render_fixed_boundary()?),
        (VARIANTS_PATH, variants),
        (OOD_PATH, ood),
    ] {
        if mode == Mode::Write {
            write_generated_file(path, &output).map_err(|e| e.to_string())?;
        } else if read_generated_file(path)? != output {
            return Err(format!("{path} is stale; run `make regenerate-pvm-constants`"));
        }
    }
    println!("PVM variant constants and shared OOD artifacts are up to date");
    Ok(())
}

/// Runtime accessors must read the same trusted metadata cells the generator initializes.
fn check_metadata_accessors() -> Result<(), String> {
    let source = read_generated_file("../lib/core/asm/sys/pvm/layout.masm")?;
    let scalars = [
        ("num_airs", 0),
        ("num_inputs_circuit", 1),
        ("num_eval_gates_circuit", 2),
        ("max_cycle_len_log", 3),
        ("max_constraint_degree", 5),
        ("num_composed_constraints", 6),
        ("num_deep_terms", 7),
        ("lookup_fractions_per_row", 8),
        ("air_fold_coefficients_ptr", 12),
        ("quotient_shift_ratio", 13),
        ("quotient_first_shift", 14),
        ("quotient_first_weight", 15),
        ("aux_rand_elem_ptr", 16),
        ("preprocessed_current_ptr", 17),
        ("aux_bus_boundary_ptr", 18),
        ("auxiliary_ace_inputs_ptr", 19),
        ("ace_circuit_stream_ptr", 20),
        ("ood_row_felts", 21),
        ("quotient_row_offset", 22),
        ("buffered_shape_value_count", 52),
        ("buffered_aux_value_count", 53),
    ];
    let words = [
        ("ace_stream_init_cv", 24),
        ("ace_circuit_digest", 28),
        ("main_lmcs_init_cv", 32),
        ("aux_lmcs_init_cv", 36),
        ("quotient_lmcs_init_cv", 40),
        ("relation_digest", 44),
        ("preprocessed_commitment", 48),
    ];
    let arrays = [
        ("air_min_log_heights_ptr", 56),
        ("air_fixed_log_heights_ptr", 68),
        ("main_ood_offsets_ptr", 80),
        ("main_ood_pipe_offsets_ptr", 92),
        ("aux_ood_offsets_ptr", 104),
        ("aux_ood_pipe_offsets_ptr", 116),
        ("ace_loader_ptr", 128),
        ("main_query_loader_ptr", 132),
        ("aux_query_loader_ptr", 136),
    ];
    for (accessors, operation) in [
        (scalars.as_slice(), "mem_load"),
        (words.as_slice(), "padw mem_loadw_le"),
        (arrays.as_slice(), "push"),
    ] {
        for &(name, offset) in accessors {
            let marker = format!("pub proc {name}()");
            let body = source
                .split_once(&marker)
                .and_then(|(_, suffix)| suffix.split_once('\n'))
                .and_then(|(_, suffix)| suffix.split_once("\nend"))
                .map(|(body, _)| body.trim())
                .ok_or_else(|| format!("missing metadata accessor {name}"))?;
            if body != format!("{operation}.{}", METADATA_START + offset) {
                return Err(format!(
                    "metadata accessor {name} disagrees with the trusted variant schema"
                ));
            }
        }
    }
    Ok(())
}

fn generated_path(relative: &str) -> String {
    format!("{}/{}", env!("CARGO_MANIFEST_DIR"), relative)
}
fn read_generated_file(relative: &str) -> Result<String, String> {
    let path = generated_path(relative);
    std::fs::read_to_string(&path).map_err(|err| format!("failed to read {path}: {err}"))
}
fn write_generated_file(relative: &str, contents: &str) -> io::Result<()> {
    std::fs::write(generated_path(relative), contents)
}
fn masm_word_literal(word: Word) -> String {
    let [a, b, c, d] = core::array::from_fn(|index| word[index].as_canonical_u64());
    format!("[{a}, {b}, {c}, {d}]")
}

fn render_pvm_parameters(
    geometry: &PvmOodGeometry,
    protocol: &relation::RelationProtocol,
    relation_digest: [Felt; 4],
    preprocessed_commitment: Word,
) -> Result<String, String> {
    let mut output = String::from(
        "# Generated by `make regenerate-pvm-constants`. Do not edit.\n\n\
         # Protocol commitments under the native Eidos configuration.\n",
    );
    for (prefix, word) in [
        ("RELATION_DIGEST", Word::new(relation_digest)),
        ("PREPROCESSED_COMMITMENT", preprocessed_commitment),
    ] {
        for (index, felt) in word.iter().enumerate() {
            writeln!(output, "pub const {prefix}_{index} = {}", felt.as_canonical_u64()).unwrap();
        }
    }
    output.push_str("\n# Security descriptor from miden_air::precompiles::security.\n");
    for (name, value) in [
        ("MAX_MESSAGE_WIDTH", u64::from(pvm_security::LOOKUP_SHAPE.max_message_width)),
        (
            "NUM_COMPOSED_CONSTRAINTS",
            u64::from(pvm_security::AIR_SHAPE.num_composed_constraints),
        ),
        (
            "MAX_CONSTRAINT_DEGREE",
            u64::from(pvm_security::AIR_SHAPE.max_constraint_degree),
        ),
        (
            "NUM_DEEP_TERMS",
            u64::from(
                pvm_security::AIR_SHAPE.num_deep_terms.expect("the PVM uses DEEP composition"),
            ),
        ),
        (
            "LOOKUP_FRACTIONS_PER_ROW",
            u64::from(pvm_security::LOOKUP_SHAPE.fractions_per_row),
        ),
        (
            "FIXED_BOUNDARY_LOOKUP_TERMS",
            u64::from(pvm_security::FIXED_BOUNDARY_LOOKUP_TERMS),
        ),
    ] {
        writeln!(output, "pub const {name} = {value}").unwrap();
    }

    output.push_str("\n# Bus-domain scale factors: BusId + 1 from the native relation registry.\n");
    for (name, bus) in [
        ("UINT_VAL_BUS_SCALE", miden_air::precompiles::relations::BusId::UintVal),
        ("EC_GROUP_BUS_SCALE", miden_air::precompiles::relations::BusId::EcGroup),
    ] {
        writeln!(output, "pub const {name} = {}", bus as usize + 1).unwrap();
    }

    let setup_height = miden_air::precompiles::primitives::byte_pair_lut::TRACE_HEIGHT;
    if !setup_height.is_power_of_two() {
        return Err("BytePairLut setup height must be a power of two".into());
    }
    let log_height = setup_height.ilog2();
    let depth = log_height
        + u32::from(miden_air::precompiles::stark_config::precompile_pcs_params().log_blowup());
    let index_mask = 1u64
        .checked_shl(depth)
        .and_then(|size| u32::try_from(size - 1).ok())
        .ok_or_else(|| "PVM preprocessed LDE depth exceeds u32 indices".to_string())?;
    output.push_str("\n# BytePairLut setup height and PCS-expanded Merkle tree.\n");
    writeln!(output, "pub const PREPROCESSED_TRACE_LOG_HEIGHT = {log_height}").unwrap();
    writeln!(output, "pub const PREPROCESSED_TREE_DEPTH = {depth}").unwrap();
    writeln!(output, "pub const PREPROCESSED_INDEX_MASK = {index_mask}").unwrap();

    output.push_str(
        "\n# Minimum log2 heights for non-fixed AIRs, indexed in ChipletAir::all() order.\n\
         # The row bound is max(2, longest periodic cycle, preprocessed trace height).\n",
    );
    for (index, height) in protocol.heights.iter().enumerate() {
        if let HeightRule::Minimum(log_height) = height {
            writeln!(output, "pub const MIN_LOG_HEIGHT_{index} = {log_height}").unwrap();
        }
    }

    output.push_str(
        "\n# Query-row blocks and LMCS leaf frames, in commitment-group order.\n\
                     # Each block contains eight base felts.\n",
    );
    for (blocks_name, init_cv_name, width) in [
        (
            "PREPROCESSED_ROW_DOUBLE_WORDS",
            "PREPROCESSED_LMCS_INIT_CV",
            geometry.preprocessed.iter().sum(),
        ),
        ("MAIN_ROW_DOUBLE_WORDS", "MAIN_LMCS_INIT_CV", geometry.main.iter().sum()),
        ("AUX_ROW_DOUBLE_WORDS", "AUX_LMCS_INIT_CV", geometry.aux.iter().sum()),
        ("QUOTIENT_ROW_DOUBLE_WORDS", "QUOTIENT_LMCS_INIT_CV", geometry.quotient),
    ] {
        if width == 0 || !width.is_multiple_of(EIDOS_BLOCK_WIDTH) {
            return Err(format!(
                "PVM {blocks_name} width {width} must be a positive multiple of {EIDOS_BLOCK_WIDTH}"
            ));
        }
        let encoded_len = u32::try_from(width)
            .map_err(|_| format!("PVM {init_cv_name} LMCS encoded length exceeds u32"))?;
        let init_cv = Eidos::init_chaining_word(LMCS_LEAF, encoded_len);
        writeln!(output, "pub const {blocks_name} = {}", width / EIDOS_BLOCK_WIDTH).unwrap();
        writeln!(output, "pub const {init_cv_name} = {}", masm_word_literal(init_cv)).unwrap();
    }
    Ok(output)
}
