//! Specialization of recursive verifier MASM from AIR definitions.
//!
//! Generated modules are tracked beside handwritten assembly. Regeneration and
//! freshness checks are explicit and never accept new protocol identities.
use std::{
    fs,
    path::{Path, PathBuf},
};

mod protocol;
mod pvm;
mod pvm_ood_frames;
mod templates;
mod vm;

/// Generator named in the header of every rendered module.
const GENERATED_BY: &str = "miden-verifier-codegen";

/// One rendered module: its path below the assembly root and its source.
pub type RenderedModule = (PathBuf, String);

/// Render every specialized verifier module from the AIR definitions and the templates.
pub fn render_verifier_masm() -> Result<Vec<RenderedModule>, String> {
    let mut modules = Vec::new();
    vm::render(&mut modules)?;
    pvm::render(&mut modules)?;
    Ok(modules)
}

/// Check tracked verifier modules, or explicitly regenerate them when `write` is set.
/// Accepted protocol identities are never updated here.
pub fn sync_verifier_masm(root: &Path, write: bool) -> Result<(), String> {
    let modules = render_verifier_masm()?;
    let mut obsolete = Vec::new();
    for relation in ["vm", "pvm"] {
        let directory = root.join("sys").join(relation);
        if !directory.exists() {
            continue;
        }
        for entry in fs::read_dir(&directory).map_err(io_error(&directory))? {
            let entry = entry.map_err(io_error(&directory))?;
            let path = entry.path();
            if !entry.file_type().map_err(io_error(&path))?.is_file()
                || path.extension().is_none_or(|extension| extension != "masm")
            {
                continue;
            }
            let source = fs::read_to_string(&path).map_err(io_error(&path))?;
            if source.starts_with(&format!("# GENERATED by `{GENERATED_BY}`"))
                && !modules.iter().any(|(module, _)| root.join(module) == path)
            {
                obsolete.push(path);
            }
        }
    }
    if !write {
        let mut drift = obsolete;
        for (module, expected) in &modules {
            let path = root.join(module);
            match fs::read_to_string(&path) {
                Ok(actual) if actual == *expected => {},
                Ok(_) => drift.push(path),
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => drift.push(path),
                Err(error) => return Err(io_error(&path)(error)),
            }
        }
        drift.sort();
        if drift.is_empty() {
            return Ok(());
        }
        return Err(format!(
            "generated verifier MASM differs; run make regenerate-verifiers:\n{}",
            drift
                .iter()
                .map(|path| path.display().to_string())
                .collect::<Vec<_>>()
                .join("\n")
        ));
    }
    for path in obsolete {
        fs::remove_file(&path).map_err(io_error(&path))?;
    }
    for (module, source) in modules {
        let path = root.join(module);
        let directory = path.parent().expect("rendered modules have a parent directory");
        fs::create_dir_all(directory).map_err(io_error(directory))?;
        fs::write(&path, source).map_err(io_error(&path))?;
    }
    Ok(())
}

fn io_error(path: &Path) -> impl Fn(std::io::Error) -> String + '_ {
    move |err| format!("{}: {err}", path.display())
}

fn push_module(
    modules: &mut Vec<RenderedModule>,
    relation: &str,
    name: &str,
    content: &str,
) -> Result<(), String> {
    if content.contains("{{") {
        return Err(format!("unexpanded template in {relation}/{name}"));
    }
    let header = format!("# GENERATED by `{GENERATED_BY}` — do not edit by hand.\n");
    let source = if content.starts_with(&header) {
        content.to_string()
    } else {
        format!("{header}{content}")
    };
    modules.push((Path::new("sys").join(relation).join(format!("{name}.masm")), source));
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Regeneration must report every form of drift instead of silently accepting a changed
    /// recursive verifier. The write mode is explicit; checking never repairs source files.
    #[test]
    fn tracked_verifiers_detect_missing_stale_and_obsolete_modules() {
        let root =
            std::env::temp_dir().join(format!("miden-verifier-freshness-{}", std::process::id()));
        fs::create_dir_all(&root).unwrap();
        assert!(sync_verifier_masm(&root, false).is_err());
        sync_verifier_masm(&root, true).unwrap();
        sync_verifier_masm(&root, false).unwrap();
        let module = root.join("sys/vm/mod.masm");
        let original = fs::read_to_string(&module).unwrap();
        fs::write(&module, format!("{original}# stale\n")).unwrap();
        assert!(sync_verifier_masm(&root, false).unwrap_err().contains("mod.masm"));
        assert!(fs::read_to_string(&module).unwrap().ends_with("# stale\n"));
        sync_verifier_masm(&root, true).unwrap();
        assert_eq!(fs::read_to_string(&module).unwrap(), original);
        let obsolete = root.join("sys/vm/obsolete.masm");
        fs::write(&obsolete, format!("# GENERATED by `{GENERATED_BY}` — do not edit by hand.\n"))
            .unwrap();
        assert!(sync_verifier_masm(&root, false).unwrap_err().contains("obsolete.masm"));
        sync_verifier_masm(&root, true).unwrap();
        assert!(!obsolete.exists());
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn rendering_expands_every_verifier_module() {
        let modules = render_verifier_masm().unwrap();
        let mut paths: Vec<_> = modules.iter().map(|(path, _)| path.clone()).collect();
        paths.sort();
        let mut expected: Vec<_> = ["vm", "pvm"]
            .into_iter()
            .flat_map(|relation| {
                ["mod", "layout", "ood_frames", "deep_queries", "constraints_eval"]
                    .map(|module| Path::new("sys").join(relation).join(format!("{module}.masm")))
            })
            .chain(
                ["aux_trace", "public_inputs"]
                    .map(|module| Path::new("sys").join("pvm").join(format!("{module}.masm"))),
            )
            .collect();
        expected.sort();
        assert_eq!(paths, expected);
        for (path, source) in &modules {
            assert!(source.starts_with("# GENERATED by"), "{} lacks its header", path.display());
            assert_eq!(
                source.matches("# GENERATED by").count(),
                1,
                "{} must carry exactly one header",
                path.display()
            );
            assert!(!source.contains("{{"), "{} has an unexpanded field", path.display());
        }
    }
}
